export type WordScriptType = 'hiragana' | 'katakana';

export interface WordEntry {
  id: string;
  display: string;          // Card heading (kanji or katakana, e.g. "食堂", "エレベーター")
  reading: string;          // Exact expected spelling in kana ("しょくどう", "エレベーター")
  scriptType: WordScriptType;
  meaning: string;          // Chinese meaning
  emoji: string;            // Clean fallback icon
  imageUrl: string;         // Local illustration path (e.g. "./images/words/w-shokudou.png")
  categoryLabel: string;    // e.g. "施設・場所", "設備", "アイテム"
  spellingTip: string;      // Concise Chinese/Japanese spelling point
  confusableWith?: string[]; // Word IDs that are commonly confused (e.g. elevator <-> escalator)
  alternateNote?: {
    input: string;          // e.g. "いえ"
    message: string;        // Friendly retry prompt without counting as a mistake
  };
  exampleJp: string;        // Short natural Japanese example sentence
  exampleZh: string;        // Chinese translation of example
  distractorChars: string[]; // 3-5 tricky distractor kana characters for Tile Builder mode
}

export interface WordDeck {
  id: string;
  title: string;
  subtitle: string;
  badge: string;
  words: WordEntry[];
}

