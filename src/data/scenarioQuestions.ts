// Procedural Endless Scenario Generator
export function generateDynamicScenarioQuestion(seedIndex: number): ScenarioQuestion {
  const mode = seedIndex % 3;

  if (mode === 0) {
    // Dynamic Price Question
    const trickyPrices = [300, 600, 800, 1300, 1600, 1800, 2400, 3000, 3600, 3800, 6800, 8000, 8600, 13000, 18000];
    const price = trickyPrices[Math.floor(Math.random() * trickyPrices.length)];
    const res = convertNumberToJapanese(price, true);
    const hasRendaku = res.segments.some((s) => s.changeType === 'rendaku');
    const hasSokuon = res.segments.some((s) => s.changeType === 'sokuon');
    const cType: SoundChangeType = hasSokuon ? 'sokuon' : hasRendaku ? 'rendaku' : 'normal';

    return {
      id: `dyn-price-${price}-${Date.now()}`,
      category: 'number_price',
      sceneName: '🏪 ふしぎ商店街・レジ会計',
      customerName: 'お買い物客',
      customerEmoji: '🛍️',
      dialogueBefore: 'お待たせしました！合計で',
      targetDisplay: res.formatted,
      dialogueAfter: 'になります。',
      fullSentenceTts: `お待たせしました！合計で${res.kanji}になります。`,
      chineseTranslation: `久等了！合计一共是 ${res.formatted}。`,
      acceptedReadings: res.alternativeHiragana,
      voiceDisplayVariants: [res.formatted, `${price}円`, res.kanji],
      changeType: cType,
      explanation:
        res.changeNotes.length > 0
          ? res.changeNotes.join(' / ')
          : `${res.formatted} ＝ 「${res.hiragana}」と読みます。`,
    };
  } else if (mode === 1) {
    // Dynamic Counter Question
    const counter = COUNTERS_DATA[Math.floor(Math.random() * COUNTERS_DATA.length)];
    const trickyCounts = [1, 2, 3, 4, 6, 8, 10];
    const count = trickyCounts[Math.floor(Math.random() * trickyCounts.length)];
    const cell = getDynamicCounterReading(counter.id, count);

    return {
      id: `dyn-cnt-${counter.id}-${count}-${Date.now()}`,
      category: 'counter',
      sceneName: `🏪 商店街・${counter.name}コーナー`,
      customerName: '常連のお客さん',
      customerEmoji: counter.emoji,
      dialogueBefore: `すみません、これ（${counter.examples.split('、')[0]}）を`,
      targetDisplay: cell.display,
      dialogueAfter: 'お願いできますか？',
      fullSentenceTts: `すみません、これを${cell.kanji}お願いできますか？`,
      chineseTranslation: `不好意思，这个（${counter.examples.split('、')[0]}）能给我来 ${cell.display} 吗？`,
      acceptedReadings: [cell.hiragana, ...(cell.altHiragana || [])],
      voiceDisplayVariants: [cell.display, cell.kanji],
      changeType: cell.changeType,
      explanation: `${cell.display}（${cell.kanji}）＝「${cell.hiragana}」。${cell.note}`,
    };
  } else {
    // Dynamic Date/Time Question
    const subType = Math.floor(Math.random() * 3);
    if (subType === 0) {
      const dayPool = DAYS_OF_MONTH_DATA.filter((d) => d.key !== '?');
      const day = dayPool[Math.floor(Math.random() * dayPool.length)];
      return {
        id: `dyn-day-${day.key}-${Date.now()}`,
        category: 'date_time',
        sceneName: '📅 商店街イベント案内所',
        customerName: '案内スタッフ',
        customerEmoji: '🗓️',
        dialogueBefore: '次回の福引き大会は、今月の',
        targetDisplay: day.display,
        dialogueAfter: 'に開催されます！',
        fullSentenceTts: `次回の福引き大会は、今月の${day.hiragana}に開催されます！`,
        chineseTranslation: `下一次抽奖大会将于本月 ${day.display} 举办！`,
        acceptedReadings: [day.hiragana, ...(day.altHiragana || [])],
        voiceDisplayVariants: [day.display, day.kanji],
        changeType: day.changeType,
        explanation: `${day.display}は「${day.hiragana}」。${day.tip}`,
      };
    } else if (subType === 1) {
      const monthPool = MONTHS_DATA.filter((m) => m.key !== '?');
      const month = monthPool[Math.floor(Math.random() * monthPool.length)];
      return {
        id: `dyn-month-${month.key}-${Date.now()}`,
        category: 'date_time',
        sceneName: '🌸 季節のカレンダー屋',
        customerName: 'カレンダー職人',
        customerEmoji: '🎋',
        dialogueBefore: '私の一番好きな季節は、',
        targetDisplay: month.display,
        dialogueAfter: 'ごろですね。',
        fullSentenceTts: `私の一番好きな季節は、${month.hiragana}ごろですね。`,
        chineseTranslation: `我最喜欢的季节大概是 ${month.display} 左右呢。`,
        acceptedReadings: [month.hiragana, ...(month.altHiragana || [])],
        voiceDisplayVariants: [month.display, month.kanji],
        changeType: month.changeType,
        explanation: `${month.display}は「${month.hiragana}」。${month.tip}`,
      };
    } else {
      const hourPool = HOURS_DATA.filter((h) => h.key !== '?');
      const minPool = MINUTES_ONE_TO_TEN.filter((m) => m.key !== '?');
      const useHour = Math.random() > 0.5;
      const item = useHour
        ? hourPool[Math.floor(Math.random() * hourPool.length)]
        : minPool[Math.floor(Math.random() * minPool.length)];
      return {
        id: `dyn-time-${item.display}-${Date.now()}`,
        category: 'date_time',
        sceneName: '🕰️ 時計塔の広場',
        customerName: '待ち合わせの学生',
        customerEmoji: '⌚',
        dialogueBefore: '時計塔の前で、ちょうど',
        targetDisplay: item.display,
        dialogueAfter: 'に待ち合わせしよう！',
        fullSentenceTts: `時計塔の前で、ちょうど${item.hiragana}に待ち合わせしよう！`,
        chineseTranslation: `我们在钟塔前正好 ${item.display} 集合吧！`,
        acceptedReadings: [item.hiragana, ...(item.altHiragana || [])],
        voiceDisplayVariants: [item.display, item.kanji],
        changeType: item.changeType,
        explanation: `${item.display}は「${item.hiragana}」。${item.tip}`,
      };
    }
  }
}

